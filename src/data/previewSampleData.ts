export const getPreviewDataForTemplate = (templateId: string, type: DocumentType): DocumentData => {
  if (type === 'resume' && templateId === 'resume-monaco-sovereign') {
    return {
      ...sampleMonacoSovereignResumeDocument,
      templateId,
    };
  }

  const base =
    type === 'biodata'
      ? previewBiodataSampleData
      : type === 'cover-letter'
      ? previewCoverLetterSampleData
      : previewResumeSampleData;
  return {
    ...base,
    templateId,
  };
};
